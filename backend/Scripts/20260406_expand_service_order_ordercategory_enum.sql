/*
  Expand allowed values for dbo.ServiceOrders.OrderCategory.
  This script is idempotent across environments with different autogenerated
  constraint names.
*/

BEGIN TRY
    BEGIN TRANSACTION;

    DECLARE @DropSql NVARCHAR(MAX) = N'';

    SELECT @DropSql = @DropSql + N'
ALTER TABLE dbo.ServiceOrders DROP CONSTRAINT ' + QUOTENAME(cc.name) + N';'
    FROM sys.check_constraints cc
    INNER JOIN sys.columns c
        ON c.object_id = cc.parent_object_id
       AND c.column_id = cc.parent_column_id
    WHERE cc.parent_object_id = OBJECT_ID(N'dbo.ServiceOrders')
      AND c.name = N'OrderCategory';

    IF LEN(@DropSql) > 0
    BEGIN
        EXEC sp_executesql @DropSql;
    END;

    ALTER TABLE dbo.ServiceOrders
    WITH CHECK ADD CONSTRAINT CK_ServiceOrders_OrderCategory
    CHECK (
        [OrderCategory] IS NULL OR
        [OrderCategory] IN (
            'QUICK_SERVICE',
            'GENERAL_REPAIR',
            'DIAGNOSIS',
            'WARRANTY',
            'MAINTENANCE',
            'INSURANCE_REPAIR',
            'REWORK',
            'WARRANTLY'
        )
    );

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0
        ROLLBACK TRANSACTION;

    THROW;
END CATCH;
